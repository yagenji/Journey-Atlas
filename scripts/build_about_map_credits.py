#!/usr/bin/env python3
"""Write the map data credits section of about/index.html.

data/map-data-sources.json lists every geographic dataset used to draw the
Country maps (sources) and which datasets each Country map is drawn from
(countries). This script renders that registry into the About page between
the map-data markers. OpenStreetMap is additionally credited inside each map
that uses it (assets/js/app.js), as ODbL requires.

Run after changing the registry; tests/test_map_credits.py fails when the
committed About page is out of date.
"""
from __future__ import annotations

import argparse
import html
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REGISTRY = ROOT / "data" / "map-data-sources.json"
ABOUT = ROOT / "about" / "index.html"
START = "    <!-- map-data:start (generated by scripts/build_about_map_credits.py) -->\n"
END = "    <!-- map-data:end -->\n"
ANCHOR = "  </main>\n"
# Datasets drawn on most maps: show the count instead of a long Country list.
SUMMARISED = {"naturalearth", "gshhg"}


def country_names() -> dict[str, str]:
    names = {}
    for path in sorted((ROOT / "data" / "countries").glob("*.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        names[data["slug"]] = data.get("nameJa") or data["slug"]
    return names


def link(url: str, text: str) -> str:
    e = html.escape
    return '<a href="%s" target="_blank" rel="noopener noreferrer">%s</a>' % (e(url), e(text))


def render_section() -> str:
    payload = json.loads(REGISTRY.read_text(encoding="utf-8"))
    sources, credits = payload["sources"], payload["countries"]
    names = country_names()
    e = html.escape
    items = []
    for source_id, source in sources.items():
        users = [slug for slug in names if source_id in credits.get(slug, [])]
        if not users:
            continue
        text = link(source["url"], source["label"])
        if source.get("license"):
            licence = link(source["licenseUrl"], source["license"]) if source.get("licenseUrl") else e(source["license"])
            text += "（%s）" % licence
        if source.get("detail"):
            text += "：%s" % e(source["detail"])
        if source_id in SUMMARISED:
            text += "全%dのうち%dの国・地域の地図で使用。" % (len(names), len(users))
        elif len(users) > 1:
            text += "使用：%s。" % e("、".join(names[slug] for slug in users))
        items.append("        <li>%s</li>\n" % text)
    return (
        START
        + '    <section class="info-section" id="map-data">\n'
        + "      <h2>地図データの出典</h2>\n"
        + "      <p>各国ページの地図は、以下の地理データをもとに、JOURNEY ATLASが投影・単純化・彩色して作成しています。"
          "OpenStreetMapのデータを使った地図には、地図の右下にも出典を表示しています。</p>\n"
        + "      <p>国境の扱いは日本政府の立場に準拠しており、元データの表示と異なる場合があります。</p>\n"
        + "      <ul>\n"
        + "".join(items)
        + "      </ul>\n"
        + "    </section>\n"
        + END
    )


def render_page() -> str:
    page = ABOUT.read_text(encoding="utf-8")
    section = render_section()
    if START in page:
        before, rest = page.split(START, 1)
        _, after = rest.split(END, 1)
        return before + section + after
    if page.count(ANCHOR) != 1:
        raise ValueError("about/index.html: expected one </main>")
    return page.replace(ANCHOR, "\n" + section + ANCHOR, 1)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if about/index.html is out of date")
    args = parser.parse_args()
    page = render_page()
    if args.check:
        if ABOUT.read_text(encoding="utf-8") != page:
            raise SystemExit("about/index.html map data section is out of date: run scripts/build_about_map_credits.py")
        print("about/index.html map data section is up to date")
        return
    ABOUT.write_text(page, encoding="utf-8")
    print("Updated about/index.html map data section")


if __name__ == "__main__":
    main()
