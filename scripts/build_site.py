def build_top_search_index() -> None:
    """Scene names / descriptions and season notes per Country, for the top-page keyword search.

    Generated from data/countries/*.json on every build so it can never drift from the Country data.
    """
    countries: dict[str, dict] = {}
    for path in sorted((ROOT / "data/countries").glob("*.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        slug = data.get("slug")
        if not slug:
            continue
        scenes = [
            [str(scene.get("name", "")).strip(), str(scene.get("nameLocal", "")).strip(), str(scene.get("description", "")).strip()]
            for scene in data.get("scenes", [])
            if scene.get("name")
        ]
        seasons = [
            [str(season.get("months", "")).strip(), str(season.get("text", "")).strip()]
            for season in data.get("seasons", [])
            if season.get("text")
        ]
        countries[slug] = {"s": scenes, "m": seasons}
    # Published Region names, Scenes and seasonal notes are searchable from TOP
    # without adding them to the 200-Country list.
    for path in sorted((ROOT / "data/regions").glob("*/*.json")):
        region = json.loads(path.read_text(encoding="utf-8"))
        if region.get("regionPublished") is not True:
            continue
        slug = region["slug"]
        if slug in countries:
            raise ValueError(f"Region search slug collides with Country: {slug}")
        countries[slug] = {
            "s": [
                [str(scene.get("name", "")).strip(), str(scene.get("nameLocal", "")).strip(),
                 str(scene.get("description", "")).strip()]
                for scene in region.get("scenes", []) if scene.get("name")
            ],
            "m": [
                [str(season.get("months", "")).strip(), str(season.get("text", "")).strip()]
                for season in region.get("seasons", []) if season.get("text")
            ],
        }
    payload = {"version": 1, "countries": countries}
    (ROOT / "data/top-search-index.json").write_text(
        json.dumps(payload, ensure_ascii=False, separators=(",", ":")) + "\n", encoding="utf-8"
    )


def build_top_season_index() -> None:
    """Recommended-season windows per Country (bestSeason), for the top-page 季節から探す.

    Generated from data/countries/*.json on every build so it can never drift from the Country data.
    Row format: slug -> [[months, label, reason], ...].
    """
    countries: dict[str, list] = {}
    for path in sorted((ROOT / "data/countries").glob("*.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        slug = data.get("slug")
        windows = (data.get("bestSeason") or {}).get("windows") or []
        if not slug or not windows:
            continue
        countries[slug] = [
            [list(window.get("months", [])), str(window.get("label", "")).strip(), str(window.get("reason", "")).strip()]
            for window in windows
        ]
    # Include published Regions in season discovery. Some Region windows store
    # only a short authored label (e.g. "12〜5月"); expand that to month numbers.
    for path in sorted((ROOT / "data/regions").glob("*/*.json")):
        region = json.loads(path.read_text(encoding="utf-8"))
        if region.get("regionPublished") is not True:
            continue
        windows = (region.get("bestSeason") or {}).get("windows") or []
        rows = []
        for window in windows:
            label = str(window.get("label", "")).strip()
            months = window.get("months")
            if not months:
                period = re.fullmatch(r"(\d{1,2})[〜～~–-](\d{1,2})月", label)
                if not period:
                    raise ValueError(f"Unparseable published Region bestSeason: {region['slug']} {label}")
                start, end = (int(v) for v in period.groups())
                if not 1 <= start <= 12 or not 1 <= end <= 12:
                    raise ValueError(f"Invalid published Region season months: {region['slug']}")
                months = list(range(start, end + 1)) if start <= end else (
                    list(range(start, 13)) + list(range(1, end + 1))
                )
            if any(not isinstance(m, int) or not 1 <= m <= 12 for m in months):
                raise ValueError(f"Invalid Region bestSeason: {region['slug']}")
            rows.append([list(months), label, str(window.get("reason", "")).strip()])
        if rows:
            if region["slug"] in countries:
                raise ValueError(f"Region season slug collides with Country: {region['slug']}")
            countries[region["slug"]] = rows
    payload = {"version": 1, "countries": countries}
    (ROOT / "data/top-season-index.json").write_text(
        json.dumps(payload, ensure_ascii=False, separators=(",", ":")) + "\n", encoding="utf-8"
    )


def build_top_scene_index() -> None:
    """Source-led labels for the top-page gallery: Scenes and Country Hero locations.

    Each Scene row is [id, name, sceneTypes]; Hero types are keyed by slug in heroTypes.

    Scene entries are published only when their thumbnail exists. Hero names come from the
    corresponding Country JSON, not from a generic country-name placeholder.
    """
    thumbs = ROOT / "assets/images/top/scenes"
    countries: dict[str, list] = {}
    heroes: dict[str, str] = {}
    hero_types: dict[str, list] = {}
    missing = 0
    for path in sorted((ROOT / "data/countries").glob("*.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        slug = data.get("slug")
        if not slug:
            continue
        hero = data.get("hero") or {}
        hero_name = str(hero.get("name") or hero.get("location") or "").strip()
        if hero.get("image") and hero_name:
            heroes[slug] = hero_name
            if hero.get("sceneTypes"):
                hero_types[slug] = hero["sceneTypes"]
        rows = []
        for scene in data.get("scenes", []):
            scene_id = scene.get("id")
            if not scene_id:
                continue
            if not (thumbs / slug / f"{scene_id}.webp").exists():
                missing += 1
                continue
            rows.append([scene_id, str(scene.get("name", "")).strip(), scene.get("sceneTypes", [])])
        if rows:
            countries[slug] = rows
    if missing:
        print(f"WARNING: {missing} Scene thumbnail(s) missing; run scripts/build_scene_thumbs.py")
    # Published Region Heroes share the existing TOP runtime index, including
    # parent metadata for map / theme / scenery discovery. They do not count as Countries.
    registry = json.loads(CORE_REGISTRY_PATH.read_text(encoding="utf-8"))
    parent_iso = {item["slug"]: item["iso2"] for item in registry["destinations"]}
    # Region flags are distinct from the parent Country flag. Reuse the
    # published UK flag artwork: Unicode subdivision flag tags do not render
    # consistently across browsers. Northern Ireland uses the UK flag.
    region_flags: dict[str, tuple[str, str | None]] = {
        "aland-islands": ("🇦🇽", None),
        "madeira": ("🇵🇹", "assets/icons/region-flags/madeira.svg"),
        "greenland": ("🇬🇱", None),
        "faroe-islands": ("🇫🇴", None),
        "aruba": ("🇦🇼", None),
        "curacao": ("🇨🇼", None),
        "sint-maarten": ("🇸🇽", None),
        "puerto-rico": ("🇵🇷", None),
        "zanzibar": ("🇹🇿", None),  # No Zanzibar subdivision emoji; use the parent Tanzania flag.
        "azores": ("🇵🇹", None),  # No Unicode subdivision flag; Portuguese autonomous region.
        "new-caledonia": ("🇳🇨", None),
        "french-polynesia": ("🇵🇫", None),
        "french-guiana": ("🇬🇫", None),
        "gibraltar": ("🇬🇮", None),
        "england": ("🏴󠁧󠁢󠁥󠁮󠁧󠁿", "assets/icons/region-flags/england-waved.svg"),
        "scotland": ("🏴󠁧󠁢󠁳󠁣󠁴󠁿", "assets/icons/region-flags/scotland-waved.svg"),
        "wales": ("🏴󠁧󠁢󠁷󠁬󠁳󠁿", "assets/icons/region-flags/wales-waved.svg"),
        "northern-ireland": ("🇬🇧", "assets/icons/region-flags/unitedkingdom-waved.svg"),
    }
    region_heroes: list[dict] = []
    for path in sorted((ROOT / "data/regions").glob("*/*.json")):
        region = json.loads(path.read_text(encoding="utf-8"))
        hero = region.get("hero") or {}
        if region.get("regionPublished") is not True or not hero.get("image"):
            continue
        parent = region["parentSlug"]
        if parent not in parent_iso:
            raise ValueError(f"Published Region missing Country parent: {parent}")
        flag_data = region_flags.get(region["slug"])
        if flag_data is None:
            raise ValueError(f"Published Region needs a TOP flag: {parent}/{region['slug']}")
        region_flag, region_flag_asset = flag_data
        if region_flag_asset and not (ROOT / region_flag_asset).is_file():
            raise FileNotFoundError(region_flag_asset)
        geo = str(region.get("region", "")).upper()
        if "NORTH AMERICA" in geo or "CARIBBEAN" in geo:
            region_id = "north-america"
        elif any(term in geo for term in ("SOUTH PACIFIC", "MELANESIA", "POLYNESIA", "OCEANIA")):
            region_id = "oceania"
        elif "EUROPE" in geo or "NORTH ATLANTIC" in geo:
            region_id = "europe"
        elif "AFRICA" in geo:
            region_id = "africa"
        elif "SOUTH AMERICA" in geo:
            region_id = "south-america"
        else:
            raise ValueError(f"Published Region needs an explicit TOP geography: {parent}/{region['slug']}")
        region_heroes.append({
            "slug": region["slug"],
            "parentSlug": parent,
            "iso2": parent_iso[parent],
            "regionId": region_id,
            "nameJa": region["nameJa"],
            "nameEn": region["nameEn"],
            "heroName": hero.get("name") or hero.get("location") or region["nameJa"],
            "flag": region_flag,
            "flagAsset": region_flag_asset,
            "travelThemes": region.get("travelThemes", []),
            "image": hero["image"],
            "sceneTypes": hero.get("sceneTypes", []),
            # Hero + Scene types for this Region page's similar-scene suggestions.
            "pageTypes": [item.get("sceneTypes", []) for item in [hero, *region.get("scenes", [])]],
            "href": f"countries/{parent}/{region['slug']}/",
        })
    # Scene types drive the top-page scene index (see data/scene-taxonomy.json).
    taxonomy = json.loads((ROOT / "data/scene-taxonomy.json").read_text(encoding="utf-8"))
    payload = {
        "version": 5, "countries": countries, "heroes": heroes, "heroTypes": hero_types,
        "regionHeroes": region_heroes, "sceneTypes": taxonomy["groups"],
    }
    (ROOT / "data/top-scene-index.json").write_text(
        json.dumps(payload, ensure_ascii=False, separators=(",", ":")) + "\n", encoding="utf-8"
    )


def main() -> int:
    clean_generated_country_pages()
    build_top_search_index()
    build_top_season_index()
    build_top_scene_index()
    bundle_css("assets/css/country.css", COUNTRY_CSS_SOURCES)
    bundle_css("assets/css/top.css", TOP_CSS_SOURCES)
    prepare_top_assets_and_js()
    prepare_app_js()
    prepare_top_page()
    prepare_generic_country_page()
    registries = load_registries()
    scope = all_destinations(registries)
    detail_slugs = {"hong-kong", "macau"}
    country_scope = [item for item in scope if item.get("slug") not in detail_slugs]
    if len(country_scope) != 200 or len(scope) != 202:
        raise ValueError(
            f"Expected 200 Country Pages plus 2 China detail regions; "
            f"found {len(country_scope)} and {len(scope) - len(country_scope)}"
        )
    published = published_destinations(registries)
    published_slugs = {item["slug"] for item in published}
    reviewable = reviewable_destinations(registries)
    urls: list[str] = []
    for item in reviewable:
        canonical = generate_country_page(item, published=item["slug"] in published_slugs)
        if item["slug"] in published_slugs:
            urls.append(canonical)
    from build_region_pages import generate_region_pages
    urls.extend(generate_region_pages(site_url=SITE_URL, version=BUILD_VERSION))
    rewrite_published_hrefs(registries)
    generate_sitemap(urls)
    print(f"Build version: {BUILD_VERSION}")
    print(
        f"Built CSS bundles, direct top media, {len(reviewable)} reviewable country page(s), "
        f"and {len(urls)} published Country/detail-region routes (200 Country Pages + 2 China details)."
    )
    return 0


