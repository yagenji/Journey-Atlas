def bundle_css(output: str, sources: list[str]) -> None:
    sections = ["/* Generated by scripts/build_site.py. Do not edit this production bundle directly. */\n"]
    for source in sources:
        path = ROOT / source
        if not path.exists():
            raise FileNotFoundError(f"CSS source missing: {source}")
        sections.append(f"\n/* ===== {source} ===== */\n")
        sections.append(path.read_text(encoding="utf-8"))
        sections.append("\n")
    (ROOT / output).write_text("".join(sections), encoding="utf-8")


def load_registries() -> list[tuple[Path, dict]]:
    registries: list[tuple[Path, dict]] = []
    for path in (CORE_REGISTRY_PATH, EDITORIAL_REGISTRY_PATH):
        if not path.exists():
            continue
        registries.append((path, json.loads(path.read_text(encoding="utf-8"))))
    return registries


def all_destinations(registries: list[tuple[Path, dict]]) -> list[dict]:
    items: list[dict] = []
    seen: set[str] = set()
    for _path, registry in registries:
        for item in registry.get("destinations", []):
            slug = item.get("slug")
            if not slug:
                raise ValueError("Destination without slug")
            if slug in seen:
                raise ValueError(f"Duplicate destination slug across registries: {slug}")
            seen.add(slug)
            items.append(item)
    return items


def published_destinations(registries: list[tuple[Path, dict]]) -> list[dict]:
    return [item for item in all_destinations(registries) if item.get("atlasPublished")]


def reviewable_destinations(registries: list[tuple[Path, dict]]) -> list[dict]:
    """Return mature country pages that may be reviewed by direct URL.

    atlasPublished controls discovery/indexing. schemaVersion=2 marks a country
    as using the current production Country Template and therefore safe to
    render as a noindex review page before publication.
    """
    items: list[dict] = []
    for item in all_destinations(registries):
        slug = item.get("slug")
        if not slug:
            continue
        path = ROOT / f"data/countries/{slug}.json"
        if not path.exists():
            continue
        data = json.loads(path.read_text(encoding="utf-8"))
        if data.get("schemaVersion") == 2:
            items.append(item)
    return items


def country_theme_labels(slug: str) -> list[str]:
    if not THEME_TAXONOMY_PATH.exists():
        return []
    taxonomy = json.loads(THEME_TAXONOMY_PATH.read_text(encoding="utf-8"))
    labels: list[str] = []
    for theme in taxonomy.get("themes", []):
        examples = theme.get("examples", [])
        if slug in examples and theme.get("label"):
            labels.append(str(theme["label"]))
    return labels


def inject_country_themes(page: str, slug: str) -> str:
    labels = country_theme_labels(slug)
    start = '      <div class="country-theme-context" id="country-theme-context" hidden>\n'
    end = '      </div>\n'
    start_index = page.find(start)
    if start_index < 0:
        raise ValueError("Country theme context marker missing from template")
    end_index = page.find(end, start_index)
    if end_index < 0:
        raise ValueError("Country theme context end marker missing from template")
    end_index += len(end)

    chips = "".join(
        f'<span class="country-theme-chip">{html.escape(label)}</span>'
        for label in labels
    )
    hidden = "" if labels else " hidden"
    replacement = (
        f'      <div class="country-theme-context" id="country-theme-context"{hidden}>\n'
        '        <span class="country-theme-context__label">TRAVEL THEMES</span>\n'
        f'        <div class="country-theme-context__list" id="country-theme-list">{chips}</div>\n'
        '      </div>\n'
    )
    return page[:start_index] + replacement + page[end_index:]


def set_tag(text: str, old: str, new: str) -> str:
    if old not in text:
        raise ValueError(f"Template marker missing: {old}")
    return text.replace(old, new, 1)


def replace_block(text: str, start: str, end: str, replacement: str) -> str:
    start_index = text.find(start)
    if start_index < 0:
        raise ValueError(f"JavaScript build marker missing: {start}")
    end_index = text.find(end, start_index)
    if end_index < 0:
        raise ValueError(f"JavaScript build end marker missing: {end}")
    return text[:start_index] + replacement + text[end_index + len(end):]


def prepare_top_assets_and_js() -> None:
    required = [
        "assets/images/top/hero-world-collage.svg",
        *[f"assets/images/top/hero-set-{index}.webp" for index in range(1, 6)],
        "assets/images/top/theme-approved-sprite.webp",
        "assets/images/top/explore-entry-sprite.webp",
    ]
    missing = [source for source in required if not (ROOT / source).exists()]
    if missing:
        raise FileNotFoundError(f"Required top assets missing: {missing}")


def prepare_app_js() -> None:
    path = ROOT / "assets/js/app.js"
    script = path.read_text(encoding="utf-8")

    site_origin_pattern = r"const SITE_ORIGIN = '[^']*';"
    if not re.search(site_origin_pattern, script):
        raise ValueError("app.js SITE_ORIGIN marker missing")
    script = re.sub(site_origin_pattern, f"const SITE_ORIGIN = '{SITE_URL}';", script, count=1)

    data_version_pattern = r"const DATA_VERSION = '[^']*';"
    if not re.search(data_version_pattern, script):
        raise ValueError("app.js DATA_VERSION marker missing")
    script = re.sub(
        data_version_pattern,
        f"const DATA_VERSION = '{BUILD_VERSION}';",
        script,
        count=1,
    )
    path.write_text(script, encoding="utf-8")


def prepare_top_page() -> None:
    path = ROOT / "index.html"
    page = path.read_text(encoding="utf-8")
    for link in TOP_CSS_LINKS:
        page = page.replace(f"  {link}\n", "")
    marker = '  <link href="https://fonts.googleapis.com/css2?family=Hanken+Grotesk:wght@400;500;600;700&family=Shippori+Mincho:wght@400;500;600&family=Zen+Kaku+Gothic+New:wght@400;500;700&display=swap" rel="stylesheet">\n'
    if 'assets/css/top.css' not in page:
        page = page.replace(marker, marker + '  <link rel="stylesheet" href="assets/css/top.css?v=20260825-1027">\n', 1)

    canonical = SITE_URL
    if 'rel="canonical"' not in page:
        page = page.replace(
            '  <title>JOURNEY ATLAS</title>\n',
            f'  <title>JOURNEY ATLAS</title>\n  <link rel="canonical" href="{canonical}">\n  <meta property="og:type" content="website">\n  <meta property="og:site_name" content="JOURNEY ATLAS">\n  <meta property="og:title" content="JOURNEY ATLAS">\n  <meta property="og:description" content="201の国・地域をイラストと地図でめぐり、次に行きたい場所を見つけるビジュアル図鑑、JOURNEY ATLAS。">\n  <meta property="og:url" content="{canonical}">\n  <meta property="og:image" content="{urljoin(SITE_URL, "assets/images/top/hero-world-collage.svg")}">\n  <meta name="twitter:card" content="summary_large_image">\n',
            1,
        )

    page = page.replace('<img id="hero-image" ', '<img id="hero-image" fetchpriority="high" ', 1)
    page = page.replace('<div class="lens-card__art"><img ', '<div class="lens-card__art"><img loading="lazy" decoding="async" ')
    path.write_text(page, encoding="utf-8")


def prepare_generic_country_page() -> None:
    path = ROOT / "country.html"
    page = path.read_text(encoding="utf-8")
    if 'name="robots"' not in page:
        page = page.replace(
            '  <meta name="description" id="meta-description"',
            '  <meta name="robots" content="noindex,follow">\n  <meta name="description" id="meta-description"',
            1,
        )

    # Country pages are HTML entry points with revalidation enabled. Give the
    # runtime JS and generated CSS a per-build URL so browsers/CDNs cannot keep
    # a stale app that requests old country JSON after a content-only deploy.
    page = re.sub(
        r'assets/js/app\.js\?v=[^"\']+',
        f'assets/js/app.js?v={BUILD_VERSION}',
        page,
        count=1,
    )
    page = re.sub(
        r'assets/css/country\.css\?v=[^"\']+',
        f'assets/css/country.css?v={BUILD_VERSION}',
        page,
        count=1,
    )
    path.write_text(page, encoding="utf-8")


def generate_country_page(destination: dict, *, published: bool) -> str:
    slug = destination["slug"]
    data_path = ROOT / f"data/countries/{slug}.json"
    if not data_path.exists():
        raise FileNotFoundError(f"Published country data missing: {data_path}")

    data = json.loads(data_path.read_text(encoding="utf-8"))

    template = (ROOT / "country.html").read_text(encoding="utf-8")
    title = f"{data['nameJa']} | {data['nameEn']} — JOURNEY ATLAS"
    description = data.get("seo", {}).get("description") or data.get("hero", {}).get("lead") or f"{data['nameJa']}を景色と地図からめぐるJOURNEY ATLAS。"
    canonical = urljoin(SITE_URL, f"countries/{slug}/")
    hero = data.get("seo", {}).get("ogImage") or data.get("hero", {}).get("image", "")
    og_image = urljoin(SITE_URL, hero) if hero else urljoin(SITE_URL, "assets/icons/favicon.svg")

    page = template
    page = set_tag(page, '<html lang="ja">', f'<html lang="ja" data-country="{html.escape(slug)}">')
    page = set_tag(page, '<head>', '<head>\n  <base href="../../">')
    page = set_tag(page, '<title>JOURNEY ATLAS — Country</title>', f'<title>{html.escape(title)}</title>')
    page = inject_country_themes(page, slug)
    page = set_tag(page, 'content="景色と地図から、次の旅先に出会う。JOURNEY ATLASの国ページ。"', f'content="{html.escape(description, quote=True)}"')
    page = set_tag(page, 'href="https://yagenji.github.io/Journey-Atlas/country.html"', f'href="{html.escape(canonical, quote=True)}"')
    page = set_tag(page, 'content="JOURNEY ATLAS — Country"', f'content="{html.escape(title, quote=True)}"')
    page = set_tag(page, 'content="景色と地図から、次の旅先に出会う。JOURNEY ATLASの国ページ。"', f'content="{html.escape(description, quote=True)}"')
    page = set_tag(page, 'content="https://yagenji.github.io/Journey-Atlas/country.html"', f'content="{html.escape(canonical, quote=True)}"')
    page = set_tag(page, 'content="https://yagenji.github.io/Journey-Atlas/assets/icons/favicon.svg"', f'content="{html.escape(og_image, quote=True)}"')
    if published:
        page = page.replace('<meta name="robots" content="noindex,follow">', '<meta name="robots" content="index,follow">', 1)

    output = ROOT / "countries" / slug / "index.html"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(page, encoding="utf-8")
    return canonical


def rewrite_published_hrefs(registries: list[tuple[Path, dict]]) -> None:
    for path, registry in registries:
        for item in registry.get("destinations", []):
            if item.get("atlasPublished") and item.get("slug"):
                item["href"] = f"countries/{item['slug']}/"
        path.write_text(json.dumps(registry, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def generate_sitemap(country_urls: list[str]) -> None:
    urls = [
        SITE_URL,
        urljoin(SITE_URL, "faq/"),
        urljoin(SITE_URL, "privacy/"),
        *country_urls,
    ]
    body = "\n".join(f"  <url><loc>{html.escape(url)}</loc></url>" for url in urls)
    xml = f'<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n{body}\n</urlset>\n'
    (ROOT / "sitemap.xml").write_text(xml, encoding="utf-8")
    (ROOT / "robots.txt").write_text(f"User-agent: *\nAllow: /\nSitemap: {urljoin(SITE_URL, 'sitemap.xml')}\n", encoding="utf-8")


def main() -> int:
    bundle_css("assets/css/country.css", COUNTRY_CSS_SOURCES)
    bundle_css("assets/css/top.css", TOP_CSS_SOURCES)
    prepare_top_assets_and_js()
    prepare_app_js()
    prepare_top_page()
    prepare_generic_country_page()
    registries = load_registries()
    scope = all_destinations(registries)
    if len(scope) != 201:
        raise ValueError(f"Expected 201 destinations, found {len(scope)}")
    published = published_destinations(registries)
    published_slugs = {item["slug"] for item in published}
    reviewable = reviewable_destinations(registries)
    urls: list[str] = []
    for item in reviewable:
        canonical = generate_country_page(item, published=item["slug"] in published_slugs)
        if item["slug"] in published_slugs:
            urls.append(canonical)
    rewrite_published_hrefs(registries)
    generate_sitemap(urls)
    print(f"Build version: {BUILD_VERSION}")
    print(
        f"Built CSS bundles, direct top media, {len(reviewable)} reviewable country page(s), "
        f"and {len(urls)} published country page(s) from 201 destinations."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
