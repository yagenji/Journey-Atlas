#!/usr/bin/env python3
"""Build production assets and static country entry pages for JOURNEY ATLAS."""

from __future__ import annotations

import html
import json
import os
import re
import subprocess
from pathlib import Path
from urllib.parse import urljoin

ROOT = Path(__file__).resolve().parents[1]
SITE_CONFIG_PATH = ROOT / "data/site.json"
CORE_REGISTRY_PATH = ROOT / "data/atlas-destinations.json"
EDITORIAL_REGISTRY_PATH = ROOT / "data/atlas-destinations-editorial.json"
THEME_TAXONOMY_PATH = ROOT / "data/theme-taxonomy.json"


def site_url() -> str:
    configured = "https://yagenji.github.io/Journey-Atlas/"
    if SITE_CONFIG_PATH.exists():
        configured = json.loads(SITE_CONFIG_PATH.read_text(encoding="utf-8")).get("baseUrl", configured)
    return os.environ.get("JOURNEY_ATLAS_SITE_URL", configured).rstrip("/") + "/"


SITE_URL = site_url()


def build_version() -> str:
    for key in ("JOURNEY_ATLAS_BUILD_VERSION", "CF_PAGES_COMMIT_SHA", "GITHUB_SHA"):
        value = os.environ.get(key, "").strip()
        if value:
            return re.sub(r"[^A-Za-z0-9._-]", "", value)[:16] or "build"
    try:
        value = subprocess.check_output(
            ["git", "rev-parse", "HEAD"],
            cwd=ROOT,
            text=True,
            stderr=subprocess.DEVNULL,
        ).strip()
        if value:
            return value[:16]
    except Exception:
        pass
    return "local"


BUILD_VERSION = build_version()

