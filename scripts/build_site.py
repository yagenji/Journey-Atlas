def site_url() -> str:
    configured = "https://yagenji.github.io/Journey-Atlas/"
    if SITE_CONFIG_PATH.exists():
        configured = json.loads(SITE_CONFIG_PATH.read_text(encoding="utf-8")).get("baseUrl", configured)
    return os.environ.get("JOURNEY_ATLAS_SITE_URL", configured).rstrip("/") + "/"


SITE_URL = site_url()


def build_version() -> str:
    for key in ("JOURNEY_ATLAS_BUILD_VERSION", "CF_PAGES_COMMIT_SHA", "GITHUB_SHA"):
        value = os.environ.get(key, "").strip()
        if value:
            return re.sub(r"[^A-Za-z0-9._-]", "", value)[:16] or "build"
    try:
        value = subprocess.check_output(
            ["git", "rev-parse", "HEAD"],
            cwd=ROOT,
            text=True,
            stderr=subprocess.DEVNULL,
        ).strip()
        if value:
            return value[:16]
    except Exception:
        pass
    return "local"


BUILD_VERSION = build_version()


def resolve_manifest_image(value: str) -> str:
    """Resolve authoring-only chunk manifests to their production image path."""
    if not isinstance(value, str) or not value.endswith(".parts.json"):
        return value
    manifest = json.loads((ROOT / value).read_text(encoding="utf-8"))
    output = manifest.get("output")
    if not isinstance(output, str) or not output.startswith("assets/images/") or ".." in Path(output).parts:
        raise ValueError(f"Image manifest output is missing/unsafe: {value}")
    return output


def versioned_approved_image(value: str) -> str:
    """Return a per-build URL for approved Country imagery.

    Source Country JSON stays stable; only generated/runtime URLs receive the
    version token. This lets browsers cache approved imagery long-term without
    serving stale content after a later deploy replaces an asset at the same path.
    """
    if not isinstance(value, str) or not value:
        return value
    if not value.startswith("assets/images/") or "/approved/" not in value:
        return value
    if "?v=" in value or "&v=" in value:
        return value
    separator = "&" if "?" in value else "?"
    return f"{value}{separator}v={BUILD_VERSION}"


